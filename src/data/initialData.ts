// Helper to generate variants for clothing (PP - XG)
const createClothingVariants = (skuPrefix: string, colors: { name: string; hex: string }[], price: number) => {
  const sizes = ['P', 'M', 'G', 'GG'];
  const variants = [];
  let id = 1;
  for (const c of colors) {
    for (const s of sizes) {
      variants.push({
        id: `${skuPrefix}-${c.name.substring(0, 3).toUpperCase()}-${s}`,
        sku: `${skuPrefix}-${s}-${c.name.substring(0, 2).toUpperCase()}`,
        size: s,
        color: c.name,
        colorHex: c.hex,
        stock: Math.floor(Math.random() * 15) + 3,
        price,
      });
      id++;
    }
  }
  return variants;
};

// Helper to generate footwear variants (38 - 44)
